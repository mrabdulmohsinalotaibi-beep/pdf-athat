'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const api=fs.readFileSync('functions/api/[[path]].js','utf8');
const client=fs.readFileSync('sync/peer-client.js','utf8');
const migration=fs.readFileSync('sync/migrations/0002_existing_accounts_peer.sql','utf8');
const build=fs.readFileSync('desktop/scripts/build-site.cjs','utf8');
for(const endpoint of ['auth/request','auth/verify','auth/session','auth/password/login','devices/revoke','peer_signals','peer_presence'])assert.ok(api.includes(endpoint),'Missing '+endpoint);
